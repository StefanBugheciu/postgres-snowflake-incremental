MERGE INTO INCREMENTAL_PIPELINE_DB.ANALYTICS.ORDERS AS target
USING INCREMENTAL_PIPELINE_DB.STAGING.BATCH_ORDERS AS source
ON target.ID = source.ID
WHEN MATCHED AND source.UPDATED_AT >= target.UPDATED_AT THEN
    UPDATE SET CUSTOMER_ID = source.CUSTOMER_ID, AMOUNT = source.AMOUNT, STATUS = source.STATUS, UPDATED_AT = source.UPDATED_AT
WHEN NOT MATCHED THEN
    INSERT (ID, CUSTOMER_ID, AMOUNT, STATUS, UPDATED_AT)
    VALUES (source.ID, source.CUSTOMER_ID, source.AMOUNT, source.STATUS, source.UPDATED_AT);
