SELECT 'customers' AS ENTITY, COUNT(*) AS ROW_COUNT, COUNT(DISTINCT ID) AS DISTINCT_IDS
FROM INCREMENTAL_PIPELINE_DB.ANALYTICS.CUSTOMERS
UNION ALL
SELECT 'orders', COUNT(*), COUNT(DISTINCT ID)
FROM INCREMENTAL_PIPELINE_DB.ANALYTICS.ORDERS;

SELECT * FROM INCREMENTAL_PIPELINE_DB.ANALYTICS.CUSTOMER_ORDER_SUMMARY ORDER BY ID;

SELECT COUNT(*) AS ORPHAN_ORDERS
FROM INCREMENTAL_PIPELINE_DB.ANALYTICS.ORDERS AS o
LEFT JOIN INCREMENTAL_PIPELINE_DB.ANALYTICS.CUSTOMERS AS c ON o.CUSTOMER_ID = c.ID
WHERE c.ID IS NULL;

SELECT STREAM, UPPER_BOUND FROM INCREMENTAL_PIPELINE_DB.CONTROL.WATERMARK;
