CREATE DATABASE IF NOT EXISTS INCREMENTAL_PIPELINE_DB;
CREATE SCHEMA IF NOT EXISTS INCREMENTAL_PIPELINE_DB.STAGING;
CREATE SCHEMA IF NOT EXISTS INCREMENTAL_PIPELINE_DB.ANALYTICS;
CREATE SCHEMA IF NOT EXISTS INCREMENTAL_PIPELINE_DB.CONTROL;

CREATE TABLE IF NOT EXISTS INCREMENTAL_PIPELINE_DB.CONTROL.WATERMARK (
    STREAM VARCHAR NOT NULL PRIMARY KEY,
    UPPER_BOUND TIMESTAMP_TZ(6) NOT NULL
);

CREATE TABLE IF NOT EXISTS INCREMENTAL_PIPELINE_DB.ANALYTICS.CUSTOMERS (
    ID NUMBER(38,0) NOT NULL, NAME VARCHAR NOT NULL, CITY VARCHAR NOT NULL, UPDATED_AT TIMESTAMP_TZ(6) NOT NULL,
    PRIMARY KEY (ID)
);

CREATE TABLE IF NOT EXISTS INCREMENTAL_PIPELINE_DB.ANALYTICS.ORDERS (
    ID NUMBER(38,0) NOT NULL, CUSTOMER_ID NUMBER(38,0) NOT NULL, AMOUNT NUMBER(12,2) NOT NULL, STATUS VARCHAR NOT NULL, UPDATED_AT TIMESTAMP_TZ(6) NOT NULL,
    PRIMARY KEY (ID)
);

CREATE VIEW IF NOT EXISTS INCREMENTAL_PIPELINE_DB.ANALYTICS.CUSTOMER_ORDER_SUMMARY AS
SELECT c.ID, c.NAME, c.CITY, COUNT(o.ID) AS ORDER_COUNT,
       SUM(IFF(o.STATUS = 'paid', o.AMOUNT, 0)) AS PAID_TOTAL
FROM INCREMENTAL_PIPELINE_DB.ANALYTICS.CUSTOMERS AS c
LEFT JOIN INCREMENTAL_PIPELINE_DB.ANALYTICS.ORDERS AS o ON c.ID = o.CUSTOMER_ID
GROUP BY c.ID, c.NAME, c.CITY;
