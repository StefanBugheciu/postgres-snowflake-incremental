MERGE INTO INCREMENTAL_PIPELINE_DB.ANALYTICS.CUSTOMERS AS target
USING INCREMENTAL_PIPELINE_DB.STAGING.BATCH_CUSTOMERS AS source
ON target.ID = source.ID
WHEN MATCHED AND source.UPDATED_AT >= target.UPDATED_AT THEN
    UPDATE SET NAME = source.NAME, CITY = source.CITY, UPDATED_AT = source.UPDATED_AT
WHEN NOT MATCHED THEN
    INSERT (ID, NAME, CITY, UPDATED_AT)
    VALUES (source.ID, source.NAME, source.CITY, source.UPDATED_AT);
